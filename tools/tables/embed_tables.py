#!/usr/bin/env python3
"""Embed assets/tables/procedural.bin as a C++ translation unit.

Usage: embed_tables.py <input.bin> <output.cpp>

The output defines faultcounter::kEmbeddedTables with the exact asset bytes so
the plug-in binary carries the 252x256 transfer tables without runtime file
access.
"""
from __future__ import annotations
import sys
from pathlib import Path

EXPECTED = 252 * 256


def main() -> None:
    src = Path(sys.argv[1])
    out = Path(sys.argv[2])
    data = src.read_bytes()
    if len(data) != EXPECTED:
        raise SystemExit(f'{src} is {len(data)} bytes; expected {EXPECTED}')
    lines = [
        '// Generated by tools/tables/embed_tables.py -- do not edit.',
        '#include "dsp/TablesData.h"',
        '',
        'namespace faultcounter',
        '{',
        'const unsigned char kEmbeddedTables[] = {',
    ]
    for offset in range(0, len(data), 16):
        chunk = ', '.join(f'0x{byte:02x}' for byte in data[offset:offset + 16])
        lines.append(f'    {chunk},')
    lines += [
        '};',
        '',
        'const unsigned kEmbeddedTablesSize = sizeof (kEmbeddedTables);',
        '} // namespace faultcounter',
        '',
    ]
    out.write_text('\n'.join(lines), encoding='utf-8')


if __name__ == '__main__':
    main()
